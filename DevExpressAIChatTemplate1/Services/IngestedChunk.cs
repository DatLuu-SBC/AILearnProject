namespace DevExpressAIChatTemplate1.Services;

public class IngestedChunk
{
    public const int VectorDimensions = 1536; // 1536 is the default vector size for the OpenAI text-embedding-3-small model
    public const string VectorDistanceFunction = "Cosine";
    //public const string CollectionName = "data-aichatwebapp2-chunks";
    public const string CollectionName = "data-aichatwebapp2-chunks-custom";

    [VectorStoreKey(StorageName = "key", IsAutoGenerated = true)]
    [JsonPropertyName("key")]
    //public required string Key { get; set; } // this work for sqlite
    public required Guid key { get; set; }

    [VectorStoreData(StorageName = "Text", IsFullTextIndexed = true)]
    [JsonPropertyName("Text")]
    public required string Text { get; set; }

    // this for document analysis or document intelligent
    [VectorStoreData(StorageName = "DocumentId")]
    [JsonPropertyName("DocumentId")]
    public required string DocumentId { get; set; }

    [VectorStoreData(StorageName = "PageNumber")]
    [JsonPropertyName("PageNumber")]
    public required int PageNumber { get; set; }

    [VectorStoreData(StorageName = "ContentType")]
    [JsonPropertyName("ContentType")]
    public string ContentType { get; set; } = "Text";

    [VectorStoreData(StorageName = "BoundingBoxJson")]
    [JsonPropertyName("BoundingBoxJson")]
    public string BoundingBoxJson { get; set; } = string.Empty;

    [VectorStoreData(StorageName = "Context")]
    [JsonPropertyName("Context")]
    public string? Context { get; set; }

    [VectorStoreVector(VectorDimensions, DistanceFunction = VectorDistanceFunction)]
    [JsonPropertyName("Embedding")]
    // public string? Vector => Text; // this work for sqlite
    public ReadOnlyMemory<float>? Vector { get; set; }
}
